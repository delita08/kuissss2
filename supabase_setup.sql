create table if not exists public.ata_scores (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 24),
  score integer not null check (score >= 0 and score <= 20),
  total integer not null default 20 check (total = 20),
  created_at timestamptz not null default now()
);
alter table public.ata_scores enable row level security;
drop policy if exists "Anyone can read quiz leaderboard" on public.ata_scores;
create policy "Anyone can read quiz leaderboard" on public.ata_scores for select to anon using (true);
drop policy if exists "Anyone can submit quiz scores" on public.ata_scores;
create policy "Anyone can submit quiz scores" on public.ata_scores for insert to anon with check (char_length(name) between 1 and 24 and score >= 0 and score <= 20 and total = 20);
